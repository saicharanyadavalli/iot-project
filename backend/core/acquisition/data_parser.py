"""Serial data parser for ESP32 and wireless sensor packets.
Extracts temperature, packet counter, and payload text from incoming serial lines.
Handles malformed messages, ESP32 boot output, and unexpected formats safely.
"""

from __future__ import annotations
import re
import json
from datetime import datetime, timezone
from dataclasses import dataclass
from typing import Optional


@dataclass
class ParsedReading:
    """Structured representation of a parsed serial reading."""
    temperature: Optional[float]
    packet_counter: Optional[int]
    raw_text: str
    timestamp: datetime
    is_valid: bool
    error_message: Optional[str] = None
    data_source: str = "physical_serial"


class DataParser:
    """Robust parser for serial streams generated by ESP32 / Arduino sensor links."""

    # Matches: [ESP32 RX] Received Packet #76: "..."
    ESP32_PACKET_PATTERN = re.compile(
        r'\[ESP32 RX\]\s*Received Packet\s*#(\d+):\s*"(.*?)"',
        re.IGNORECASE
    )

    # Matches temperature in payloads: Temp: 24.5 C, Temperature: 24.5, T=24.5, etc.
    TEMP_PATTERN = re.compile(
        r'(?:temp(?:erature)?[:=\s]*)([+-]?\d+(?:\.\d+)?)\s*(?:[°C|C|degC])?',
        re.IGNORECASE
    )

    # Matches standalone float or signed float: e.g. "24.5", "+25.10", "  23.8  "
    STANDALONE_FLOAT = re.compile(r'^\s*([+-]?\d+(?:\.\d+)?)\s*(?:[°C|C])?\s*$')

    # Matches Nano ping packets: Ping from Nano #76
    NANO_PING_PATTERN = re.compile(r'Ping from Nano\s*#(\d+)', re.IGNORECASE)

    def __init__(self, parse_mode: str = "auto", ping_demo_baseline: float = 24.5):
        """
        Args:
            parse_mode: 'auto' extracts float from payload; if only Ping packet is present,
                        can interpret as live ping test or flag missing.
                        'strict' requires explicit numeric temperature.
            ping_demo_baseline: baseline temp used only if ping_demo mode is enabled.
        """
        self.parse_mode = parse_mode
        self.ping_demo_baseline = ping_demo_baseline

    def parse_line(self, line: str, timestamp: Optional[datetime] = None) -> ParsedReading:
        """Parse a single serial line. Never throws exceptions on malformed input."""
        ts = timestamp or datetime.now(timezone.utc)
        if not line or not isinstance(line, str):
            return ParsedReading(
                temperature=None,
                packet_counter=None,
                raw_text=str(line),
                timestamp=ts,
                is_valid=False,
                error_message="Empty or non-string serial data"
            )

        clean_line = line.strip()
        if not clean_line:
            return ParsedReading(
                temperature=None,
                packet_counter=None,
                raw_text=line,
                timestamp=ts,
                is_valid=False,
                error_message="Blank line"
            )

        # 1. Check for standard [ESP32 RX] Received Packet #N: "..." format
        rx_match = self.ESP32_PACKET_PATTERN.search(clean_line)
        if rx_match:
            counter = int(rx_match.group(1))
            payload = rx_match.group(2).strip()
            temp = self._extract_temperature(payload)
            
            if temp is not None:
                return ParsedReading(
                    temperature=temp,
                    packet_counter=counter,
                    raw_text=clean_line,
                    timestamp=ts,
                    is_valid=True
                )
            
            # Check if payload is "Ping from Nano #N"
            ping_match = self.NANO_PING_PATTERN.search(payload)
            if ping_match:
                if self.parse_mode == "ping_demo":
                    # Derive small dynamic variation for hardware demonstration without sensor
                    jitter = ((counter % 10) - 5) * 0.1
                    derived_temp = round(self.ping_demo_baseline + jitter, 2)
                    return ParsedReading(
                        temperature=derived_temp,
                        packet_counter=counter,
                        raw_text=clean_line,
                        timestamp=ts,
                        is_valid=True
                    )
                else:
                    return ParsedReading(
                        temperature=None,
                        packet_counter=counter,
                        raw_text=clean_line,
                        timestamp=ts,
                        is_valid=False,
                        error_message=f"Received wireless ping packet #{counter} with no temperature payload"
                    )

            return ParsedReading(
                temperature=None,
                packet_counter=counter,
                raw_text=clean_line,
                timestamp=ts,
                is_valid=False,
                error_message=f"Unrecognized payload content: '{payload}'"
            )

        # 2. Check for JSON format: {"temperature": 24.5} or {"temp": 24.5}
        if clean_line.startswith('{') and clean_line.endswith('}'):
            try:
                data = json.loads(clean_line)
                temp = data.get("temperature", data.get("temp"))
                if temp is not None:
                    return ParsedReading(
                        temperature=float(temp),
                        packet_counter=data.get("counter"),
                        raw_text=clean_line,
                        timestamp=ts,
                        is_valid=True
                    )
            except (json.JSONDecodeError, ValueError, TypeError):
                pass

        # 3. Check for direct temperature string: "Temp: 24.5 C" or "Temperature: 24.5"
        temp = self._extract_temperature(clean_line)
        if temp is not None:
            return ParsedReading(
                temperature=temp,
                packet_counter=None,
                raw_text=clean_line,
                timestamp=ts,
                is_valid=True
            )

        # 4. Check for standalone float: "24.5"
        standalone = self.STANDALONE_FLOAT.match(clean_line)
        if standalone:
            try:
                return ParsedReading(
                    temperature=float(standalone.group(1)),
                    packet_counter=None,
                    raw_text=clean_line,
                    timestamp=ts,
                    is_valid=True
                )
            except ValueError:
                pass

        return ParsedReading(
            temperature=None,
            packet_counter=None,
            raw_text=clean_line,
            timestamp=ts,
            is_valid=False,
            error_message="Could not extract valid temperature measurement"
        )

    def _extract_temperature(self, text: str) -> Optional[float]:
        """Extract temperature float from text like 'Temp: 24.5 C' or '24.5 C'."""
        match = self.TEMP_PATTERN.search(text)
        if match:
            try:
                val = float(match.group(1))
                return round(val, 2)
            except (ValueError, TypeError):
                pass

        standalone = self.STANDALONE_FLOAT.match(text)
        if standalone:
            try:
                return round(float(standalone.group(1)), 2)
            except (ValueError, TypeError):
                pass

        return None
